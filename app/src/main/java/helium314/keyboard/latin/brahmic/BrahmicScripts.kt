package helium314.keyboard.latin.brahmic

/**
 * Per-script Brahmic classification, derived from Unicode Indic_Syllabic_Category
 * and character names. Vedic Extensions are Inherited and do not resolve here.
 */
class BrahmicScript(
    val name: String,
    internal val blocks: IntArray,
    val viramaToInsert: Int,
    internal val viramas: IntArray,
    val nukta: Int,
    val inherentVowel: Int,
    internal val binduVisarga: IntArray,
    internal val consonants: IntArray,
    internal val independentVowels: IntArray,
    internal val dependentVowels: IntArray,
    internal val families: IntArray,
    internal val twoPartVowels: IntArray,
) {
    private val independentToDependent = HashMap<Int, Int>()
    private val dependentToIndependent = HashMap<Int, Int>()
    private val twoPartComposed = HashMap<Long, Int>()

    init {
        var i = 0
        while (i < families.size) {
            independentToDependent[families[i]] = families[i + 1]
            dependentToIndependent[families[i + 1]] = families[i]
            i += 2
        }
        i = 0
        while (i < twoPartVowels.size) {
            val key = twoPartKey(twoPartVowels[i], twoPartVowels[i + 1])
            twoPartComposed[key] = twoPartVowels[i + 2]
            i += 3
        }
    }

    fun contains(codePoint: Int): Boolean {
        var i = 0
        while (i < blocks.size) {
            if (codePoint in blocks[i]..blocks[i + 1]) return true
            i += 2
        }
        return false
    }

    fun isVirama(codePoint: Int) = codePoint in viramas
    fun isNukta(codePoint: Int) = nukta >= 0 && codePoint == nukta
    fun isAyogavaha(codePoint: Int) = codePoint in binduVisarga
    fun isConsonant(codePoint: Int) = codePoint in consonants
    fun isIndependentVowel(codePoint: Int) = codePoint in independentVowels
    fun isDependentVowel(codePoint: Int) = codePoint in dependentVowels
    fun isVowel(codePoint: Int) = isIndependentVowel(codePoint) || isDependentVowel(codePoint)
    fun isInherentA(codePoint: Int) = inherentVowel >= 0 && codePoint == inherentVowel
    fun hasNukta() = nukta >= 0
    fun hasVirama() = viramaToInsert >= 0

    fun toDependent(codePoint: Int): Int? {
        if (isDependentVowel(codePoint)) return codePoint
        return independentToDependent[codePoint]
    }

    fun toIndependent(codePoint: Int): Int? {
        if (isIndependentVowel(codePoint)) return codePoint
        return dependentToIndependent[codePoint]
    }

    fun familyOf(codePoint: Int): Pair<Int, Int>? {
        val independent = independentToDependent[codePoint]
        if (independent != null) return codePoint to independent
        val dependent = dependentToIndependent[codePoint]
        if (dependent != null) return dependent to codePoint
        return null
    }

    fun nfcTwoPart(first: Int, second: Int): Int? =
        twoPartComposed[twoPartKey(first, second)]

    fun twoPartDependentLength(cps: IntArray, lastIndex: Int): Int {
        if (lastIndex < 1) return 1
        val composed = nfcTwoPart(cps[lastIndex - 1], cps[lastIndex]) ?: return 1
        return if (isDependentVowel(composed)) 2 else 1
    }

    fun isIndependentTwoPart(first: Int, second: Int): Boolean {
        val composed = nfcTwoPart(first, second) ?: return false
        return isIndependentVowel(composed)
    }

    fun classificationSets(): List<IntArray> = listOf(
        independentVowels, dependentVowels, consonants, viramas,
        if (nukta >= 0) intArrayOf(nukta) else intArrayOf(),
        binduVisarga,
    )

    companion object {
        private fun twoPartKey(first: Int, second: Int) =
            (first.toLong() shl 32) or (second.toLong() and 0xFFFFFFFFL)
    }
}

