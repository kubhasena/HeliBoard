    /** Script owning [codePoint], or null for Vedic/Inherited/unknown. */
    @JvmStatic
    fun forCodePoint(codePoint: Int): BrahmicScript? {
        for (script in all) if (script.contains(codePoint)) return script
        return null
    }

    fun isVowel(codePoint: Int) = forCodePoint(codePoint)?.isVowel(codePoint) == true

    @JvmStatic
    fun isAyogavaha(codePoint: Int) = forCodePoint(codePoint)?.isAyogavaha(codePoint) == true

    /** Vowels, matras, and ayogavahas (bindu / visarga / candrabindu) get the letter-key tint. */
    @JvmStatic
    fun tintsLetterKey(code: Int, label: String): Boolean {
        if (code > 0 && tintsLetterCodePoint(code)) return true
        if (label.isEmpty() || label[0] == '!') return false
        val first = label.codePointAt(0)
        return tintsLetterCodePoint(first) || leadingVowel(label) >= 0
    }

    private fun tintsLetterCodePoint(codePoint: Int): Boolean {
        val script = forCodePoint(codePoint) ?: return false
        return script.isVowel(codePoint) || script.isAyogavaha(codePoint)
    }

    /**
     * The vowel a key label stands for. Marks may ride along after it, as in आं or াঁ.
     * A decomposed two-part matra such as ে + া counts as one vowel.
     *
     * @return the (composed, if two-part) code point, or -1
     */
    fun leadingVowel(label: String): Int {
        if (label.isEmpty()) return -1
        val first = label.codePointAt(0)
        val script = forCodePoint(first) ?: return -1
        if (!script.isVowel(first)) return -1
        var i = Character.charCount(first)
        if (i < label.length) {
            val second = label.codePointAt(i)
            val composed = script.nfcTwoPart(first, second)
            if (composed != null && script.isVowel(composed)) {
                i += Character.charCount(second)
                while (i < label.length) {
                    val cp = label.codePointAt(i)
                    if (isVowel(cp)) return -1
                    i += Character.charCount(cp)
                }
                return composed
            }
        }
        while (i < label.length) {
            val cp = label.codePointAt(i)
            if (isVowel(cp)) return -1
            i += Character.charCount(cp)
        }
        return first
    }

    fun leadingVowelLength(label: String): Int {
        if (label.isEmpty()) return 0
        val first = label.codePointAt(0)
        val script = forCodePoint(first) ?: return 0
        if (!script.isVowel(first)) return 0
        val firstLen = Character.charCount(first)
        if (firstLen < label.length) {
            val second = label.codePointAt(firstLen)
            val composed = script.nfcTwoPart(first, second)
            if (composed != null && script.isVowel(composed)) {
                return firstLen + Character.charCount(second)
            }
        }
        return firstLen
    }
